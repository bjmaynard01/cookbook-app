"""Password hashing and verification service (auth plan S3, R2 + O-f).

Pure service — no database, no environment or ``SECRET_KEY`` dependency.

Policy (owner-approved O-f, 2026-10-16):
* A *new* password must be at least :data:`MINIMUM_LENGTH` code points.
  There are **no** complexity or character-class rules. ``validate_password``
  and ``hash_password`` enforce it; nothing is trimmed, normalized, case-
  folded, or silently truncated, and there is no maximum length or additional
  character restriction.
* ``verify_password`` does **not** apply the new-password policy: passwords
  stored before this policy existed keep verifying against their original
  hashes.

Hashing:
* argon2id (Argon2 ``Type.ID``) via :mod:`argon2` (argon2-cffi), configured
  at the OWASP minimum the plan locks (at or above is allowed by §6.2):
  memory_cost=19456 KiB (19 MiB), time_cost=2, parallelism=1, hash_len=32,
  salt_len=16. A fresh secure salt is generated by the library for every
  :func:`hash_password` call, so two hashes of the same password differ.
* No hashing is performed at import time. :data:`DUMMY_HASH` below is a
  committed, non-secret constant (generated once at development time) so the
  module body never has to run the slow hash.

Verification:
* ``verify_password`` performs exactly one library verification against the
  supplied stored hash. Correct password → ``True``; mismatch or malformed /
  unsupported stored hash → ``False`` (caught on the documented argon2
  exceptions specifically — never a broad ``Exception``). It never echoes a
  password or a hash into any returned value, message, or log line.

Dummy path:
* :func:`dummy_verify` exists so a login attempt for a *username that does
  not exist* still performs one full argon2id verification instead of
  returning instantly — removing a timing side-channel that would let an
  attacker enumerate which usernames already exist. It calls the library
  verifier exactly once with the submitted candidate and :data:`DUMMY_HASH`,
  then discards the outcome and returns ``None``. It authenticates no one.
* A caller chooses either :func:`verify_password` (known user) or
  :func:`dummy_verify` (unknown user) for a single attempt, never both, so
  the expensive hash work is not doubled.
* This is comparably expensive hash work (not a promise of mathematically
  constant total request latency).
"""
from __future__ import annotations

from argon2 import PasswordHasher, Type, extract_parameters
from argon2 import exceptions as argon2_exc

# O-f minimum length, in Python ``str`` code points. No complexity rules.
MINIMUM_LENGTH = 8

# Clear, fixed policy message — deliberately contains no password material.
_POLICY_MESSAGE = (
    f"Password must be at least {MINIMUM_LENGTH} characters long; no "
    "complexity requirements apply."
)

# The single configured hasher for the whole service. Constructed at import
# time (cheap — no hashing is performed); used by every hash/verify call.
_hasher = PasswordHasher(
    type=Type.ID,
    memory_cost=19456,   # 19 MiB, in KiB units (argon2-cffi convention)
    time_cost=2,
    parallelism=1,
    hash_len=32,         # 256-bit hash
    salt_len=16,         # 128-bit salt, generated securely per hash
)

# Committed non-secret dummy hash (Argon2id, same parameters as above).
# Pre-generated once at development time rather than computed on import or
# per call, so importing this module never performs argon2id work. Used by
# ``dummy_verify`` to burn comparable work for unknown-user attempts; it is
# not a real credential and does not verify to any known password.
DUMMY_HASH = (
    "$argon2id$v=19$m=19456,t=2,p=1"
    "$pIWrDBClE2SJ4pIw1IHV6g"
    "$Q4vHoOrQ+/UBH4Z41Kkxfx2rGkV5myILGAoUmDsAWfY"
)


def validate_password(plain: str) -> None:
    """Enforce the new-password policy for ``plain`` and return ``None``.

    Raises ``ValueError`` (message :data:`_POLICY_MESSAGE`) if ``plain`` has
    fewer than :data:`MINIMUM_LENGTH` code points. Any string meeting the
    minimum is accepted — no trimming, Unicode normalization, case folding,
    maximum length, or character-class restriction. Unicode code points count
    as characters. The error message never contains any part of ``plain``.
    """
    if len(plain) < MINIMUM_LENGTH:
        raise ValueError(_POLICY_MESSAGE)


def hash_password(plain: str) -> str:
    """Return a fresh argon2id hash of a new password for storage.

    Applies :func:`validate_password`, then hashes ``plain`` with a fresh
    library-generated secure salt. Because the salt differs each call, two
    hashes of the same password are different strings, but both verify.
    """
    validate_password(plain)
    return _hasher.hash(plain)


def verify_password(plain: str, stored_hash: str) -> bool:
    """Check ``plain`` against ``stored_hash`` for a known user.

    Returns ``True`` when they match, ``False`` when they do not, and
    ``False`` when ``stored_hash`` is malformed or unsupported. Performs
    exactly one library verification; raises only on unexpected programming
    / resource failures (those are re-raised by design, not swallowed).

    This does NOT apply the new-password policy: a password stored before
    :data:`MINIMUM_LENGTH` was introduced (and shorter than it) still
    verifies against its existing hash here.
    """
    # Exception classification (argon2-cffi 25.1.0). The library raises:
    #   * VerifyMismatchError            — candidate did not match (a genuine
    #                                       authentication failure) -> False.
    #   * InvalidHashError (a ValueError,
    #                                       NOT an Argon2Error) — clearly
    #                                       malformed stored hash -> False.
    #   * UnsupportedParametersError     — stored hash parameters this platform
    #                                       cannot honor (bad stored data)
    #                                       -> False.
    #   * VerificationError (the *generic* parent of VerifyMismatchError) —
    #     the library CONFLATES two very different outcomes under this one
    #     class: (a) a recognized-prefix-but-malformed body ("Decoding
    #     failed"), and (b) an operational failure on a structurally-valid
    #     hash ("Memory cost is too small"). We must NOT blanket-catch it,
    #     or we would disguise a real resource failure as a normal
    #     wrong-password. Instead we discriminate by structural validity.
    # MemoryError / RuntimeError from the C layer are intentionally never
    # caught and propagate.
    try:
        _hasher.verify(stored_hash, plain)
        return True
    except argon2_exc.VerifyMismatchError:
        # Genuine mismatch — a normal "no", never a leak of any password or
        # hash value.
        return False
    except (argon2_exc.InvalidHashError, argon2_exc.UnsupportedParametersError):
        # Stored hash is malformed, or its parameters are not supported on
        # this platform: bad stored data -> a normal "no".
        return False
    except argon2_exc.VerificationError:
        # Conflated case. ``extract_parameters`` (a documented library
        # primitive) returns the parsed parameters for a well-formed hash and
        # raises InvalidHashError for a malformed one, which lets us cleanly
        # separate "bad stored data" (-> False) from "operational failure"
        # (-> re-raise). A successful parse proves the hash is structurally
        # valid, so the VerificationError must have come from actually
        # performing verification work.
        try:
            extract_parameters(stored_hash)
        except argon2_exc.InvalidHashError:
            return False
        raise  # structurally valid hash -> operational failure: surface it


def dummy_verify(plain: str) -> None:
    """Perform one full argon2id verification so an unknown-user attempt has
    comparable cost to a known-user failure.

    Calls the library verifier exactly once with the submitted candidate
    ``plain`` and the committed :data:`DUMMY_HASH`, then discards the result
    and returns ``None``. It never authenticates anyone and returns no
    authentication outcome.

    Callers choose either :func:`verify_password` (known user) or
    :func:`dummy_verify` (unknown user) per attempt, not both — do not
    double the hash work. This yields comparable (not mathematically
    constant) verification cost without a cheap unknown-user path that a
    timing attack could use for username enumeration.
    """
    # The committed DUMMY_HASH is controlled application data we know to be
    # well-formed and structurally valid, so the ONLY normal failure mode here
    # is a genuine candidate mismatch. Catch exactly that one class
    # (VerifyMismatchError) and discard the result: dummy_verify authenticates
    # no one and reports no outcome.
    #
    # Deliberately do NOT catch the broader Argon2Error family, the generic
    # VerificationError, or InvalidHashError / UnsupportedParametersError:
    # because DUMMY_HASH is our own (not attacker-supplied) constant, any of
    # those reaching this point indicates a real environmental or data-integrity
    # problem — a malformed/unsupported dummy hash, or an operational
    # verification failure (VerificationError "Memory …", MemoryError,
    # RuntimeError) — and must propagate to a caller rather than be mistaken
    # for a benign unknown-user login attempt.
    try:
        _hasher.verify(DUMMY_HASH, plain)
    except argon2_exc.VerifyMismatchError:
        # Normal outcome for a non-matching candidate on a valid dummy hash;
        # discard it. A successful match (library returning True) is also
        # simply discarded — either way dummy_verify returns None and
        # authenticates nothing.
        return None
    return None
